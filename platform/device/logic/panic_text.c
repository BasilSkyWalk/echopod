static const uint8_t *rows_of(char character)
{
    for (size_t index = 0; index < sizeof GLYPHS / sizeof GLYPHS[0]; index++) {
        if (GLYPHS[index].character == character) {
            return GLYPHS[index].rows;
        }
    }
    return NULL;
}

static uint16_t pixel_at(const uint8_t *rows, int row, int column, PanicColors colors)
{
    if (rows == NULL || column >= PANIC_GLYPH_COLUMNS) {
        return colors.background;
    }
    bool lit = (rows[row] >> (PANIC_GLYPH_COLUMNS - 1 - column) & 1u) != 0;
    return lit ? colors.foreground : colors.background;
}

void panic_render_glyph(char character, int scale, PanicColors colors, uint16_t *pixels)
{
    const uint8_t *rows = rows_of(character);
    int width = PANIC_GLYPH_ADVANCE * scale;
    for (int y = 0; y < PANIC_GLYPH_ROWS * scale; y++) {
        for (int x = 0; x < width; x++) {
            pixels[y * width + x] = pixel_at(rows, y / scale, x / scale, colors);
        }
    }
}
